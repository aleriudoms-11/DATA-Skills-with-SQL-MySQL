# REAL WORLD EXAMPLE OF JOIN QUERIES:

-- WE ARE GOING TO CREATE TWO TABLES:
-- 1) CUSTOMER
-- 2) EVENT

CREATE TABLE CUSTOMER (
    CUSTOMER_ID INT PRIMARY KEY AUTO_INCREMENT,
    NAME VARCHAR(50),
    ADDRESS VARCHAR(255)
);

INSERT INTO CUSTOMER (NAME, ADDRESS)
VALUES
('CASEY', '2295 SPRING AVENUE'),
('PETER', '924 EMMA STREET'),
('ERIKA', '397 TERRY LANE');

SELECT * FROM CUSTOMER;

CREATE TABLE EVENT (
    EVENT_ID INT PRIMARY KEY,
    CUSTOMER_ID INT,
    ACTION VARCHAR(255)
);

INSERT INTO EVENT (EVENT_ID, CUSTOMER_ID, ACTION)
VALUES
(101, 3, 'LOGIN'),
(102, 3, 'VIEW PAGE'),
(103, 1, 'LOGIN'),
(104, 1, 'SEARCH');

SELECT * FROM EVENT;

-- QUESTION 1: WHO ARE THE ACTIVE USERS?
-- QUESTION 2: WHO ARE THE USERS THAT HAVE PERFORMED AN ACTION?

SELECT * FROM CUSTOMER 
INNER JOIN EVENT 
ON CUSTOMER.CUSTOMER_ID = EVENT.CUSTOMER_ID;

-- QUESTION 3: SELECT ALL USERS FROM THE CUSTOMER TABLE AND ONLY THE ACTIONS THAT THESE USERS HAVE DONE:

SELECT * FROM CUSTOMER 
LEFT JOIN EVENT 
ON CUSTOMER.CUSTOMER_ID = EVENT.CUSTOMER_ID;

